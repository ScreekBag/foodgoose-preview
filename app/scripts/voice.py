"""Records the voice-over: one MP3 per paragraph through the private Kut voice studio
(ElevenLabs via Vercel AI Gateway), then writes src/content/audio.ts.

  KUT_STUDIO_KEY_FILE=/path/to/secret python3 scripts/voice.py [--voice ID] [--only intro,stop:sadu] [--sample]
"""
import argparse, json, os, subprocess, sys, tempfile, time, urllib.request, urllib.error

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.normpath(os.path.join(HERE, '..'))
ROUTE = json.load(open(os.path.join(APP, 'src', 'content', 'route.json'), encoding='utf-8'))
OUT = os.path.join(APP, 'assets', 'audio')
HOST = os.environ.get('KUT_STUDIO_HOST', 'https://kut-voice-studio.vercel.app')

def tracks():
    yield 'intro', ROUTE['intro']
    for s in ROUTE['stops']:
        yield f"stop:{s['id']}", s['script']
        for i, m in enumerate(s['more']):
            yield f"story:{s['id']}:{i}", m['text']
    yield 'outro', ROUTE['outro']

def fname(track): return track.replace(':', '_')

def tts(key, text, voice, model):
    body = json.dumps({'text': text, 'voice': voice, 'model': model}).encode()
    for attempt in range(4):
        req = urllib.request.Request(HOST + '/api/tts', data=body, headers={'Content-Type': 'application/json', 'x-studio-key': key})
        try:
            return urllib.request.urlopen(req, timeout=280).read()
        except urllib.error.HTTPError as e:
            msg = e.read()[:300]
            if e.code in (401, 400): raise SystemExit(f'HTTP {e.code}: {msg}')
            print(f'  retry after HTTP {e.code}: {msg}', file=sys.stderr)
        except Exception as e:
            print(f'  retry after {e}', file=sys.stderr)
        time.sleep(5 * (attempt + 1))
    raise SystemExit('voice studio did not answer')

def shrink(raw, dest):
    """Mono 64 kbps keeps the whole route around 20 MB."""
    with tempfile.NamedTemporaryFile(suffix='.mp3') as tmp:
        tmp.write(raw); tmp.flush()
        subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', tmp.name, '-ac', '1', '-b:a', '64k', dest], check=True)

def manifest():
    lines = ['// Generated by scripts/voice.py — one recorded MP3 per paragraph, keyed by track id.',
             'export const audio: Record<string, number[]> = {']
    for track, paras in tracks():
        d = os.path.join(OUT, fname(track))
        files = [os.path.join(d, f'{i:02d}.mp3') for i in range(len(paras))]
        if all(os.path.exists(f) for f in files):
            reqs = ', '.join(f"require('../../assets/audio/{fname(track)}/{i:02d}.mp3')" for i in range(len(paras)))
            lines.append(f"  '{track}': [{reqs}],")
    lines.append('};')
    open(os.path.join(APP, 'src', 'content', 'audio.ts'), 'w').write('\n'.join(lines) + '\n')

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--voice', default='JBFqnCBsd6RMkjVDRZzb')
    ap.add_argument('--model', default='elevenlabs/eleven-v3')
    ap.add_argument('--only', default='')
    ap.add_argument('--force', action='store_true')
    a = ap.parse_args()
    key = open(os.environ['KUT_STUDIO_KEY_FILE']).read().strip()
    only = set(filter(None, a.only.split(',')))
    for track, paras in tracks():
        if only and track not in only: continue
        d = os.path.join(OUT, fname(track)); os.makedirs(d, exist_ok=True)
        for i, p in enumerate(paras):
            dest = os.path.join(d, f'{i:02d}.mp3')
            if os.path.exists(dest) and not a.force: continue
            shrink(tts(key, p, a.voice, a.model), dest)
            print(f'{track} {i + 1}/{len(paras)}')
    manifest()
    print('manifest written')

if __name__ == '__main__':
    main()
